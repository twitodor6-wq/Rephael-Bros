  check('Parallax, existing particles and atmosphere remain enabled',state['depth']['enabled'] and state['ambience']['enabled'] and len(state['depth']['loaded'])==3)
  check('legacy M4.6 bridge collider disabled',state['bridge']['legacyDisabled'] and state['bridge']['safe'],state=state['bridge'])
  check('new 169px walkable bridge outside pit',state['bridge']['bounds']=={'x':718,'y':399,'w':169,'h':15} and state['bridge']['decorativeGap']>75)
  check('cosmetic-only stage dressing loaded',state['dressing']['enabled'] and state['dressing']['groundCount']==2)
  p.screenshot(path=str(R/'evidence/m461-stage-initial.png'))
  p.click('#rb-stage-tab');check('panel expands by click and tracks aria',p.locator('#rb-stage-panel').is_visible() and p.locator('#rb-stage-tab').get_attribute('aria-expanded')=='true')
  p.screenshot(path=str(R/'evidence/m461-stage-sidebar.png'))
  p.click('#rb-m461-dressing-toggle');p.wait_for_timeout(70)
  check('new stage dressing can be toggled independently',p.evaluate('__RBStageDressing.snapshot().enabled')==False)
  p.click('#rb-m461-dressing-toggle');p.wait_for_timeout(60)
  p.click('#rb-m46-ambience-toggle');p.wait_for_timeout(100)
  check('existing ambience toggle works inside panel',p.evaluate('window.__RBForestAmbienceEnabled')==False)
  p.click('#rb-m46-ambience-toggle')
  p.click('#rb-m46-parallax-toggle');p.wait_for_timeout(100)
  check('existing parallax toggle preserved',p.evaluate('window.__RBForestParallaxEnabled')==False)
  p.click('#rb-m46-parallax-toggle');p.wait_for_timeout(150)
  check('parallax restored original art state',p.evaluate('window.__RBForestParallaxEnabled')==True and p.evaluate('__RBForestParallax.snapshot().sprites.mid.alpha')>.2)
  p.locator('#rb-module-hazards summary').click();p.click('#rb-m44-web-toggle',timeout=5000);p.wait_for_timeout(80)
  check('original sticky-web toggle preserved',p.evaluate('window.__RBStickyWebEnabled')==False)
  p.click('#rb-m44-web-toggle')
  p.click('#rb-m45-egg-toggle');p.wait_for_timeout(80)
  check('original egg-sac toggle preserved',p.evaluate('window.__RBEggSacEnabled')==False)
  p.click('#rb-m45-egg-toggle')
  p.click('#rb-m46-bridges-toggle');p.wait_for_timeout(150)
  check('bridges disable both visual and new collision',not p.evaluate('__RBBridgePolish.snapshot().colliderActive'))
  p.click('#rb-m46-bridges-toggle');p.wait_for_timeout(160)
  check('bridges re-enable new geometry',p.evaluate('__RBBridgePolish.snapshot().colliderActive'))
  p.click('#rb-m42-art-toggle');p.wait_for_timeout(130)
